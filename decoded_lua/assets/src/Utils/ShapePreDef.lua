function defShape(def)

	if (nil == def or 0 == #def
		or nil == def[1] or 0 == #def[1]) then
		return nil
	end

	local shape = ShapeLogic.new({
		row = #def,
		column =  #def[1],
	})

	for i = 1, #def do
		for j = 1, #def[1] do
			if (1 == def[i][j]) then
				shape:turnOn(i, j)
			end
		end
	end

	return shape

end

